import { basename, resolve } from 'node:path'
import fs from 'node:fs'

const SRC_DIR = './src'
const OUT_DIR = './lib'
const OUT_FILE = `${OUT_DIR}/events.d.ts`
const EXCLUDED_BASENAMES = new Set(['main', 'common-properties', 'empty-event'])
const COMMON_DEF_REF_PREFIX = 'common-properties#/definitions/'

const snakeToCamel = (key) => key.replace(/_([\da-z])/gu, (_, char) => char.toUpperCase())
const pascalize = (key) => key.charAt(0).toUpperCase() + key.slice(1)

const isIdentifier = (key) => /^[$A-Z_a-z][\w$]*$/u.test(key)
const formatKey = (key) => (isIdentifier(key) ? key : JSON.stringify(key))
const literal = (value) => JSON.stringify(value)
const indent = (level) => '  '.repeat(level)

const getFiles = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(dir, entry.name)
    return entry.isDirectory() ? getFiles(path) : path
  })

const emitType = (node, level) => {
  if (!node || typeof node !== 'object') return 'unknown'

  if ('const' in node) return literal(node.const)

  if (Array.isArray(node.enum)) {
    return node.enum.map((value) => literal(value)).join(' | ')
  }

  if (Array.isArray(node.anyOf)) {
    return node.anyOf.map((sub) => emitType(sub, level)).join(' | ')
  }

  if (Array.isArray(node.oneOf)) {
    return node.oneOf.map((sub) => emitType(sub, level)).join(' | ')
  }

  if (Array.isArray(node.type)) {
    return node.type.map((t) => emitType({ ...node, type: t }, level)).join(' | ')
  }

  switch (node.type) {
    case 'string':
      return 'string'
    case 'number':
    case 'integer':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return `Array<${emitType(node.items || {}, level)}>`
    case 'object':
      return emitObject(node, level)
    default:
      return 'unknown'
  }
}

const emitObject = (node, level) => {
  const properties = node.properties || {}
  const required = new Set(node.required || [])
  const keys = Object.keys(properties)
  if (keys.length === 0) return '{}'

  const inner = keys.map((key) => {
    const camelKey = snakeToCamel(key)
    const optional = required.has(key) ? '' : '?'
    const type = emitType(properties[key], level + 1)
    return `${indent(level + 1)}${formatKey(camelKey)}${optional}: ${type}`
  })

  return ['{', ...inner, `${indent(level)}}`].join('\n')
}

const getCommonDefRefs = (eventSchema, knownDefs) => {
  const allOf = eventSchema?.properties?.properties?.allOf
  if (!Array.isArray(allOf)) return []
  return allOf
    .map((entry) => entry?.$ref)
    .filter((ref) => typeof ref === 'string' && ref.startsWith(COMMON_DEF_REF_PREFIX))
    .map((ref) => ref.slice(COMMON_DEF_REF_PREFIX.length))
    .filter((name) => knownDefs.has(name))
}

const buildEventArm = (schema, knownDefs) => {
  const name = schema.properties.event.const
  const propsSchema = schema.properties.properties
  const ownProps = emitObject(propsSchema, 1)
  const refTypes = getCommonDefRefs(schema, knownDefs).map((def) => pascalize(def))
  const arm = refTypes.length === 0 ? ownProps : [ownProps, ...refTypes].join(' & ')
  return `${indent(1)}${literal(name)}: ${arm}`
}

const main = () => {
  const allFiles = getFiles(SRC_DIR)
    .filter((path) => path.endsWith('.schemasafe.json'))
    .sort()

  const commonPath = allFiles.find((path) => basename(path) === 'common-properties.schemasafe.json')
  if (!commonPath) throw new Error('common-properties.schemasafe.json not found')
  const commonSchema = JSON.parse(fs.readFileSync(commonPath, 'utf8'))
  const definitions = commonSchema.definitions || {}
  const knownDefs = new Set(Object.keys(definitions))

  const eventSchemas = allFiles
    .filter((path) => {
      const baseName = basename(path).replace(/\.schemasafe\.json$/u, '')
      return !EXCLUDED_BASENAMES.has(baseName)
    })
    .map((path) => JSON.parse(fs.readFileSync(path, 'utf8')))
    .filter((schema) => schema?.properties?.event?.const && schema?.properties?.properties)
    .sort((a, b) => a.properties.event.const.localeCompare(b.properties.event.const))

  const definitionTypes = Object.entries(definitions)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, schema]) => `export type ${pascalize(name)} = ${emitObject(schema, 0)}`)

  const lines = [
    '// AUTOGENERATED by scripts/build-types.mjs — DO NOT EDIT.',
    '// Source of truth: src/**/*.schemasafe.json',
    '',
    `export type AnalyticsCommonProperties = ${emitObject(commonSchema, 0)}`,
    '',
    ...definitionTypes.flatMap((line) => [line, '']),
    'export interface AnalyticsEventMap {',
    ...eventSchemas.map((schema) => buildEventArm(schema, knownDefs)),
    '}',
    '',
    'export type AnalyticsEventName = keyof AnalyticsEventMap',
    '',
    'export type AnalyticsEventProperties<E extends AnalyticsEventName> =',
    `${indent(1)}AnalyticsEventMap[E] & AnalyticsCommonProperties`,
    '',
    'type RequiredKeys<T> = { [K in keyof T]-?: ({} extends Pick<T, K> ? never : K) }[keyof T]',
    '',
    'export type AnalyticsEventPayload<E extends string = string> = E extends AnalyticsEventName',
    `${indent(1)}? RequiredKeys<AnalyticsEventProperties<E>> extends never`,
    `${indent(2)}? { event: E; properties?: AnalyticsEventProperties<E> }`,
    `${indent(2)}: { event: E; properties: AnalyticsEventProperties<E> }`,
    `${indent(1)}: { event: E; properties?: AnalyticsCommonProperties }`,
    '',
  ]

  fs.mkdirSync(OUT_DIR, { recursive: true })
  fs.writeFileSync(OUT_FILE, lines.join('\n'))
  process.stdout.write(`Wrote ${OUT_FILE} (${eventSchemas.length} events)\n`)
}

main()
